#!/usr/bin/env bash
set -euo pipefail

# SecCam installation script for Debian 12
# Usage: install.sh [--pin PIN] [--retention DAYS]
# Run as root. Idempotent and safe for upgrades.

PIN=""
RETENTION_DAYS=""

while [[ $# -gt 0 ]]; do
    case $1 in
        --pin)
            PIN="${2:-}"
            shift 2
            ;;
        --retention)
            RETENTION_DAYS="${2:-}"
            shift 2
            ;;
        *)
            echo "Unknown option: $1" >&2
            echo "Usage: $0 [--pin PIN] [--retention DAYS]" >&2
            exit 1
            ;;
    esac
done

if [[ $EUID -ne 0 ]]; then
    echo "This script must be run as root" >&2
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
INSTALL_DIR="/opt/seccam"
DATA_DIR="/var/lib/seccam"
CONFIG_DIR="/etc/seccam"
TLS_DIR="$CONFIG_DIR/tls"
SERVICE_FILE="/etc/systemd/system/seccam.service"
ENV_FILE="$CONFIG_DIR/seccam.env"

echo "=== SecCam Installation v1.1.0 ==="
echo "Install directory: $INSTALL_DIR"
echo "Data directory: $DATA_DIR"
echo "Config directory: $CONFIG_DIR"

# Install system dependencies
echo "Installing system packages..."
apt-get update -qq
apt-get install -y --no-install-recommends \
    python3 python3-venv openssl ca-certificates curl git \
    >/dev/null

# Create system user
if ! id -u seccam >/dev/null 2>&1; then
    echo "Creating system user 'seccam'..."
    useradd --system --no-create-home --home-dir "$DATA_DIR" --shell /usr/sbin/nologin seccam
else
    echo "User 'seccam' already exists"
fi

# Create directories
mkdir -p "$DATA_DIR" "$CONFIG_DIR" "$TLS_DIR"
chown seccam:seccam "$DATA_DIR"
chmod 750 "$DATA_DIR"
chmod 750 "$CONFIG_DIR"
chmod 750 "$TLS_DIR"

# Copy application files
echo "Copying application to $INSTALL_DIR..."
mkdir -p "$INSTALL_DIR"
# Remove old server/ and static/ dirs but keep data
rm -rf "$INSTALL_DIR/server" "$INSTALL_DIR/static" "$INSTALL_DIR/models"
cp -a "$PROJECT_ROOT/server" "$INSTALL_DIR/"
cp -a "$PROJECT_ROOT/static" "$INSTALL_DIR/"
if [[ -d "$PROJECT_ROOT/models" ]]; then
    cp -a "$PROJECT_ROOT/models" "$INSTALL_DIR/"
fi
cp -a "$PROJECT_ROOT/requirements.txt" "$INSTALL_DIR/"
find "$INSTALL_DIR/server" -name "__pycache__" -prune -exec rm -rf {} +
chown -R root:root "$INSTALL_DIR"   # code is read-only for the service user
# Ensure static and models are readable by seccam user
find "$INSTALL_DIR/static" -type f -exec chmod 644 {} + 2>/dev/null || true
find "$INSTALL_DIR/static" -type d -exec chmod 755 {} + 2>/dev/null || true
if [[ -d "$INSTALL_DIR/models" ]]; then
    find "$INSTALL_DIR/models" -type f -exec chmod 644 {} + 2>/dev/null || true
    find "$INSTALL_DIR/models" -type d -exec chmod 755 {} + 2>/dev/null || true
fi

# Create virtual environment and install Python dependencies
echo "Setting up Python virtual environment..."
if [[ ! -d "$INSTALL_DIR/venv" ]]; then
    python3 -m venv "$INSTALL_DIR/venv"
fi
"$INSTALL_DIR/venv/bin/pip" install --upgrade pip -q
"$INSTALL_DIR/venv/bin/pip" install --no-cache-dir -r "$INSTALL_DIR/requirements.txt" -q

# Generate TLS certificates
echo "Generating TLS certificates..."
"$SCRIPT_DIR/gen-certs.sh" "$TLS_DIR"

# Prepare environment file
echo "Writing environment file: $ENV_FILE"
if [[ -f "$ENV_FILE" ]]; then
    # Preserve existing values unless overridden by flags
    # shellcheck disable=SC1090
    source "$ENV_FILE" 2>/dev/null || true
fi
# Flags win over existing values; defaults apply on first install
SECCAM_PIN="${PIN:-${SECCAM_PIN:-}}"
SECCAM_RETENTION_DAYS="${RETENTION_DAYS:-${SECCAM_RETENTION_DAYS:-14}}"
if [[ -n "$SECCAM_PIN" ]] && ! [[ "$SECCAM_PIN" =~ ^[0-9]{4,12}$ ]]; then
    echo "PIN must be 4-12 digits" >&2
    exit 1
fi
if ! [[ "$SECCAM_RETENTION_DAYS" =~ ^[0-9]+$ ]]; then
    echo "retention must be a number of days" >&2
    exit 1
fi

# Determine primary IP for display
PRIMARY_IP=$( { hostname -I 2>/dev/null || ip -4 -o addr show scope global | awk '{print $4}' | cut -d/ -f1; } | tr ' ' '\n' | grep -E '^[0-9.]+$' | head -1 )

cat > "$ENV_FILE" <<EOF
# SecCam environment configuration
# Generated by install.sh on $(date -Iseconds)
# Do not edit manually; re-run install.sh to change values

SECCAM_PIN=$SECCAM_PIN
SECCAM_SECRET=${SECCAM_SECRET:-}
SECCAM_DATA_DIR=${SECCAM_DATA_DIR:-$DATA_DIR}
SECCAM_RETENTION_DAYS=$SECCAM_RETENTION_DAYS
SECCAM_MODEL_PATH=${SECCAM_MODEL_PATH:-$INSTALL_DIR/models/yolox_nano.onnx}
SECCAM_HOST=${SECCAM_HOST:-0.0.0.0}
SECCAM_HTTPS_PORT=${SECCAM_HTTPS_PORT:-443}
SECCAM_HTTP_PORT=${SECCAM_HTTP_PORT:-80}
SECCAM_CERT=${SECCAM_CERT:-$TLS_DIR/server.crt}
SECCAM_KEY=${SECCAM_KEY:-$TLS_DIR/server.key}
SECCAM_CA_CERT=${SECCAM_CA_CERT:-$TLS_DIR/ca.crt}
SECCAM_STATIC_DIR=${SECCAM_STATIC_DIR:-$INSTALL_DIR/static}
EOF

chmod 640 "$ENV_FILE"
chown root:seccam "$ENV_FILE"

# Source the written env file so we have the correct ports for health check
# shellcheck disable=SC1090
source "$ENV_FILE" 2>/dev/null || true

# Install systemd service
echo "Installing systemd service..."
cp "$SCRIPT_DIR/seccam.service" "$SERVICE_FILE"
systemctl daemon-reload
systemctl enable seccam.service

# Start or restart service
if systemctl is-active --quiet seccam.service; then
    echo "Restarting seccam service..."
    systemctl restart seccam.service
else
    echo "Starting seccam service..."
    systemctl start seccam.service
fi

# Wait for health endpoint
echo "Waiting for service to become healthy..."
HEALTHY=0
for _ in {1..20}; do
    if curl -k -s -f "https://127.0.0.1:${SECCAM_HTTPS_PORT}/api/health" >/dev/null 2>&1; then
        HEALTHY=1
        break
    fi
    sleep 1
done

if [[ $HEALTHY -eq 0 ]]; then
    echo "ERROR: Service failed to become healthy within 20 seconds" >&2
    echo "=== Recent logs ===" >&2
    journalctl -u seccam -n 50 --no-pager >&2
    exit 1
fi

echo ""
echo "=== Installation Complete ==="
if [[ -n "$SECCAM_PIN" ]]; then
    echo "Viewer URL:      https://$PRIMARY_IP/"
    echo "Camera URL:      https://$PRIMARY_IP/camera"
    echo "Setup URL:       https://$PRIMARY_IP/setup"
    echo "CA Certificate:  https://$PRIMARY_IP/ca.crt"
    echo ""
    echo "PIN: $SECCAM_PIN"
else
    echo "No PIN configured — first-run setup required."
    echo "Open in browser: https://$PRIMARY_IP/"
    echo "CA Certificate:  http://$PRIMARY_IP/ca.crt  (for iPhone trust)"
fi
echo "Data directory: $DATA_DIR"
echo ""
echo "To change PIN or retention, re-run: $0 [--pin NEW_PIN] [--retention DAYS]"
